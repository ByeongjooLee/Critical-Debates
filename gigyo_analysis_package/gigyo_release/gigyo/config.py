# ── 표지 엔진용 선언 헬퍼 ──────────────────────────────────
PatItem = Tuple[Optional[str], Optional[str]]  # (form|None, tag-prefix|None)


def _lex(*forms) -> List[dict]:
    """어휘형: 형태소 form 정확 일치(부사 등)."""
    return [{"label": f, "kind": "lex", "value": f} for f in forms]


def _con(label: str, pattern: List[PatItem]) -> dict:
    """구문형: 형태소열 순서/근접 패턴."""
    return {"label": label, "kind": "con", "value": pattern}


def _sur(label: str, surface: str) -> dict:
    """표면형: 공백 유연(\\s*) 정규식(다어절 표현)."""
    rx = re.escape(surface).replace(r"\ ", r"\s*")
    return {"label": label, "kind": "sur", "value": rx}


